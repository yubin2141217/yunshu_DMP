def write_markdown(out: Path) -> None:
    header = """---
title: "功能清单"
subtitle: "物流配送后台管理系统"
author: "物流企业（客户单位待定）"
date: "编制单位：项目组\\n\\n二零二六年五月"
lang: zh-CN
geometry: "left=2.54cm,right=2.54cm,top=2.54cm,bottom=2.54cm"
---

## 文档信息

| 项目名称 | 物流配送后台管理系统 |
|---------|----------------------|
| 文档版本 | V1.0 |
| 编制日期 | 2026-05-07 |
| 编制人 | 项目组 |
| 文档状态 | 草稿 |

**数据来源：** 《物流配送后台管理系统 SRS 需求规格说明书》V1.0 — 第 3.2、3.3 节

---

## 功能清单

本期仅建设 **PC 端管理后台**，故不列「所属系统」。

| 模块 | 子模块 | 功能名称 | 功能描述 | 优先级 | 备注 |
|------|--------|---------|---------|-------|------|
"""
    lines = []
    for m, sm, fn, desc, pr in ROWS:
        sm_d = sm if sm != "-" else "—"
        lines.append(
            f"| {m} | {sm_d} | {fn} | {desc} | {pr} | |"
        )
    footer = """

---

**说明：**

- 优先级与 SRS 第 3.2 节业务需求对应：运单中心、调度与任务、在途监控、系统治理等为 **P0**；仓储衔接、客服与异常、财务与对账为 **P1**（货主侧协同能力体现在对接与运单数据贯通中）。
- 功能粒度与 SRS 第 3.3 节「页面功能清单」一致。
"""
    out.write_text(header + "\n".join(lines) + footer, encoding="utf-8")


def excel_payload() -> dict:
    header = ["模块", "子模块", "功能名称", "功能描述", "优先级", "备注"]
    data = [header]
    for m, sm, fn, desc, pr in ROWS:
        sm_d = "—" if sm == "-" else sm
        data.append([m, sm_d, fn, desc, pr, ""])
    return {
        "filename": "2026-05-07-物流配送后台管理系统-功能清单-V1.0",
        "title": "物流配送后台管理系统功能清单",
        "freezeFirstRow": True,
        "autoFilter": True,
        "sheets": [{"name": "功能清单", "data": data}],
    }


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    out_md = (
        root
        / "docs"
        / "01-需求与规划"
        / "2026-05-07-物流配送后台管理系统-功能清单-V1.0.md"
    )
    write_markdown(out_md)
    print(f"Wrote {out_md}")
    payload_path = root / "docs" / "01-需求与规划" / "_feature-list-export.json"
    payload_path.write_text(
        json.dumps(excel_payload(), ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    print(f"Wrote {payload_path}")


if __name__ == "__main__":
    main()
